package io.ballerina.persist.dataservice;

import io.ballerina.compiler.syntax.tree.SyntaxInfo;
import io.ballerina.compiler.syntax.tree.SyntaxTree;
import io.ballerina.persist.BalException;
import io.ballerina.persist.nodegenerator.syntax.constants.BalSyntaxConstants;
import io.ballerina.persist.nodegenerator.syntax.utils.BalSyntaxUtils;
import io.ballerina.tools.diagnostics.Diagnostic;
import io.ballerina.tools.diagnostics.DiagnosticSeverity;
import io.ballerina.tools.text.TextDocuments;
import org.ballerinalang.formatter.core.Formatter;
import org.ballerinalang.formatter.core.FormatterException;

import java.util.regex.Pattern;

/**
 * Helpers shared by the data service model readers and the generator.
 */
final class DataServiceUtils {

    // Splits a camel-case name into its words, keeping an acronym such as `HTTP` as one word.
    static final Pattern WORD_BOUNDARY = Pattern.compile("(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])");
    static final String NEWLINE = System.lineSeparator();

    private static final Pattern IDENTIFIER = Pattern.compile("[A-Za-z_][A-Za-z0-9_]*");

    private DataServiceUtils() {
    }

    static String unescape(String name) {
        return BalSyntaxUtils.stripEscapeCharacter(name.startsWith("'") ? name.substring(1) : name);
    }

    static String unquote(String text) {
        return text.length() >= 2 && text.startsWith("\"") && text.endsWith("\"") ?
                text.substring(1, text.length() - 1) : text;
    }

    static boolean isInternal(FieldRules.Applied rule) {
        return rule != null && rule.rule() == FieldRule.INTERNAL;
    }

    // A file the build tool writes is not to be edited; one that `bal persist generate` writes is the user's.
    static String header(String reason, boolean userOwned) {
        if (userOwned) {
            return "// AUTO-GENERATED FILE." + NEWLINE + NEWLINE + reason + NEWLINE + NEWLINE;
        }
        return BalSyntaxConstants.AUTOGENERATED_FILE_COMMENT + NEWLINE + NEWLINE + reason + NEWLINE +
                BalSyntaxConstants.COMMENT_SHOULD_NOT_BE_MODIFIED + NEWLINE + NEWLINE;
    }

    static String servicePath(String basePath) {
        if ("/".equals(basePath)) {
            return "/";
        }
        for (String segment : basePath.substring(1).split("/")) {
            if (!IDENTIFIER.matcher(segment).matches() || SyntaxInfo.isKeyword(segment)) {
                return "\"" + basePath + "\"";
            }
        }
        return basePath;
    }

    // A syntax error is reported with its line, so that a broken template is found from the message.
    static String format(String source) throws BalException {
        SyntaxTree tree = SyntaxTree.from(TextDocuments.from(source));
        for (Diagnostic diagnostic : tree.diagnostics()) {
            if (diagnostic.diagnosticInfo().severity() == DiagnosticSeverity.ERROR) {
                int line = diagnostic.location().lineRange().startLine().line();
                throw new BalException(String.format("failed to format the data service source: %s at line %d: %s",
                        diagnostic.message(), line + 1, tree.textDocument().line(line).text().strip()));
            }
        }
        try {
            return Formatter.format(tree).toSourceCode();
        } catch (FormatterException e) {
            throw new BalException("failed to format the data service source. " + e.getMessage());
        }
    }
}
